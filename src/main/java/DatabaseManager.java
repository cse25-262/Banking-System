import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public final class DatabaseManager {
    private static final String DEFAULT_URL = "jdbc:h2:file:./data/banking";
    private DatabaseManager() { }

    public static Connection getConnection() throws SQLException {
        String url = System.getProperty("bank.db.url", DEFAULT_URL);
        return DriverManager.getConnection(url, "sa", "");
    }

    public static void initialize() {
        String[] ddl = {
            "CREATE TABLE IF NOT EXISTS customers (username VARCHAR(80) PRIMARY KEY, first_name VARCHAR(100) NOT NULL, surname VARCHAR(100) NOT NULL, address VARCHAR(250), phone_number VARCHAR(40), password_hash VARCHAR(200) NOT NULL)",
            "CREATE TABLE IF NOT EXISTS accounts (account_number VARCHAR(30) PRIMARY KEY, customer_username VARCHAR(80) NOT NULL, account_type VARCHAR(20) NOT NULL, balance DOUBLE PRECISION NOT NULL, branch VARCHAR(120) NOT NULL DEFAULT 'Gaborone', employer_name VARCHAR(150), employer_address VARCHAR(250), last_interest_period CHAR(7), FOREIGN KEY (customer_username) REFERENCES customers(username) ON DELETE CASCADE)",
            "ALTER TABLE accounts ADD COLUMN IF NOT EXISTS branch VARCHAR(120) NOT NULL DEFAULT 'Gaborone'",
            "ALTER TABLE accounts ADD COLUMN IF NOT EXISTS last_interest_period CHAR(7)",
            "CREATE TABLE IF NOT EXISTS transactions (transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_number VARCHAR(30) NOT NULL, transaction_type VARCHAR(20) NOT NULL, amount DOUBLE PRECISION NOT NULL, description VARCHAR(250), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (account_number) REFERENCES accounts(account_number) ON DELETE CASCADE)"
        };
        try (Connection connection = getConnection(); Statement statement = connection.createStatement()) {
            for (String sql : ddl) statement.execute(sql);
        } catch (SQLException e) {
            throw new IllegalStateException("Could not initialize the banking database.", e);
        }
    }
}
